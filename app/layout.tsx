import '../styles/globals.css'
import { cookies } from 'next/headers'
import AppBar from '../components/AppBar'
import AppTheme from '../components/AppTheme'
import { CommandPaletteProvider } from '../components/CommandPalette'
import styles from './layout.module.css'

export const metadata = {
  title: 'GunHyuk',
  description: 'Generated by Next.js',
}

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode
}) {
  const savedTheme = (await cookies()).get('home-theme')?.value
  const initialTheme = savedTheme === 'light' || savedTheme === 'dark' ? savedTheme : undefined

  return (
    <html lang="en" className={initialTheme === 'light' ? '' : 'dark'}>
      <body>
        <AppTheme className={styles.shell} initialTheme={initialTheme}>
          <CommandPaletteProvider>
            <AppBar />
            <div className={styles.content}>{children}</div>
          </CommandPaletteProvider>
        </AppTheme>
      </body>
    </html>
  )
}
